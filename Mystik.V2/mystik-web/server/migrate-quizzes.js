function migrateQuizzes() {
  const db = getDatabase();
  
  console.log('Начинаем миграцию тестов с полными вопросами...');
  
  try {
    // Очищаем существующие тесты
    db.prepare('DELETE FROM quizzes').run();
    
    // Добавляем тесты в базу данных
    const insertQuiz = db.prepare(`
      INSERT INTO quizzes (id, title, description, is_premium, questions, created_at)
      VALUES (?, ?, ?, ?, ?, ?)
    `);
    
    for (const [id, quiz] of Object.entries(QUIZZES_DATA)) {
      const now = new Date().toISOString();
      insertQuiz.run(
        id,
        quiz.title,
        quiz.description,
        quiz.isPremium ? 1 : 0,
        JSON.stringify(quiz.questions),
        now
      );
      console.log(`✓ Добавлен тест: ${quiz.title} (${quiz.questions.length} вопросов)`);
    }
    
    console.log('Миграция тестов завершена успешно!');
    
    // Проверяем результат
    const count = db.prepare('SELECT COUNT(*) as count FROM quizzes').get();
    console.log(`Всего тестов в базе: ${count.count}`);
    
  } catch (error) {
    console.error('Ошибка при миграции тестов:', error);
    process.exit(1);
  }
}

// Запускаем миграцию
migrateQuizzes();